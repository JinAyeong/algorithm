SELECT
    NB.AUTHOR_ID,
    NB.AUTHOR_NAME,
    NB.CATEGORY,
    SUM(NB.PRICE * BS.SALES) AS TOTAL_SALES
FROM (
    SELECT
        B.BOOK_ID,
        B.CATEGORY,
        B.AUTHOR_ID,
        A.AUTHOR_NAME,
        B.PRICE,
        B.PUBLISHED_DATE
    FROM BOOK B
    JOIN AUTHOR A ON B.AUTHOR_ID = A.AUTHOR_ID
) NB
CROSS JOIN BOOK_SALES BS ON BS.BOOK_ID = NB.BOOK_ID
WHERE DATE_FORMAT(BS.SALES_DATE, '%y-%m') = '22-01'
GROUP BY AUTHOR_ID, CATEGORY
ORDER BY AUTHOR_ID, CATEGORY DESC;


---불필요한 서브쿼리 제거

SELECT
    A.AUTHOR_ID,
    A.AUTHOR_NAME,
    B.CATEGORY,
    SUM(B.PRICE * BS.SALES) AS TOTAL_SALES
FROM BOOK B
JOIN AUTHOR A
    ON B.AUTHOR_ID = A.AUTHOR_ID
JOIN BOOK_SALES BS
    ON B.BOOK_ID = BS.BOOK_ID
WHERE BS.SALES_DATE >= '2022-01-01'
  AND BS.SALES_DATE < '2022-02-01'
GROUP BY
    A.AUTHOR_ID,
    A.AUTHOR_NAME,
    B.CATEGORY
ORDER BY
    A.AUTHOR_ID ASC,
    B.CATEGORY DESC;