SELECT
    MONTH(START_DATE) AS MONTH,
    CAR_ID,
    COUNT(*) AS RECORDS
FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY
WHERE CAR_ID IN (
    SELECT CAR_ID
    FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY
    WHERE START_DATE >= '2022-08-01' AND START_DATE <= '2022-10-31'
    GROUP BY CAR_ID
    HAVING COUNT(*) >= 5
) AND START_DATE >= '2022-08-01' AND START_DATE <= '2022-10-31'
GROUP BY CAR_ID, MONTH(START_DATE)
ORDER BY MONTH, CAR_ID DESC

--윈도우 함수
SELECT
    MONTH,
    CAR_ID,
    MONTHLY_CNT AS RECORDS
FROM (
    SELECT
        CAR_ID,
        MONTH(START_DATE) AS MONTH,
        COUNT(*) OVER (PARTITION BY CAR_ID) AS TOTAL_CNT,
        COUNT(*) OVER (PARTITION BY CAR_ID, MONTH(START_DATE)) AS MONTHLY_CNT
    FROM CAR_RENTAL_COMPANY_RENTAL_HISTORY
    WHERE MONTH(START_DATE) >= 8 AND MONTH(START_DATE) <= 10
) T
WHERE TOTAL_CNT >= 5
GROUP BY CAR_ID, MONTH
ORDER BY MONTH, CAR_ID DESC